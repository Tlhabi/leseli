/* Leseli build script – no dependencies, Node 16+.
   node tools/build.js           -> checks content, writes app/sw.js, copies app into the Android project,
                                    and makes dist/leseli-offline.html (one file, works in any browser)
   Everything in app/ already runs as-is; this script only packages it. */
const fs = require('fs'), path = require('path'), crypto = require('crypto'), vm = require('vm');
const ROOT = path.join(__dirname, '..'), APP = path.join(ROOT, 'app'), DIST = path.join(ROOT, 'dist');
const walk = d => fs.readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
const files = walk(APP).filter(f => !/sw\.js$|\.DS_Store/.test(f)).map(f => path.relative(APP, f).split(path.sep).join('/')).sort();

/* 1. content checks: load every script in a fake browser and validate lessons */
const html = fs.readFileSync(path.join(APP, 'index.html'), 'utf8');
const scripts = [...html.matchAll(/<script src="([^"]+)"/g)].map(m => m[1]);
const fakeEl = () => new Proxy(function () {}, { get: (t, k) => k === Symbol.toPrimitive ? () => '' : fakeEl(), apply: () => fakeEl(), construct: () => fakeEl() });
const ctx = { window: {}, document: { addEventListener() {}, createElement: () => fakeEl(), querySelector: () => null, querySelectorAll: () => [] }, navigator: {}, localStorage: { getItem: () => null, setItem() {} }, location: { hash: '' }, console };
ctx.window = ctx; vm.createContext(ctx);
let problems = 0;
for (const s of scripts) { try { vm.runInContext(fs.readFileSync(path.join(APP, s), 'utf8'), ctx, { filename: s }); } catch (e) { console.error('✘ script error in', s, e.message); problems++; } }
const LES = vm.runInContext('LESELI', ctx);
const lessons = Object.values(LES.lessons); const ids = new Set();
lessons.forEach(l => {
  if (ids.has(l.id)) { console.error('✘ duplicate id', l.id); problems++; } ids.add(l.id);
  if (![5, 6, 7].includes(l.grade)) { console.error('✘ bad grade', l.id); problems++; }
  if (!l.title || !l.title.en || !l.title.st) { console.error('✘ missing title', l.id); problems++; }
  (l.sections || []).forEach((s, i) => { if (!s.p || !s.p.en || !s.p.st) { console.error('✘ section text missing', l.id, i); problems++; } });
  (l.quiz || []).forEach((q, i) => { if (q.o && (q.a < 0 || q.a >= q.o.length)) { console.error('✘ answer out of range', l.id, i); problems++; } if (!q.o && q.n === undefined) { console.error('✘ empty question', l.id, i); problems++; } });
  if (!(l.quiz || []).length) { console.error('✘ no quiz', l.id); problems++; }
});
const per = {}; lessons.forEach(l => { const k = l.subject + ' G' + l.grade; per[k] = (per[k] || 0) + 1; });
const qn = lessons.reduce((a, l) => a + (l.quiz || []).length, 0);
console.log(`✔ ${lessons.length} lessons, ${qn} quiz questions, ${LES.words.length} dictionary words, ${LES.stories.length} stories, ${LES.riddles.length} riddles, ${LES.proverbs.length} proverbs`);
console.log('  ' + Object.entries(per).map(([k, v]) => `${k}: ${v}`).join(' · '));
if (problems) { console.error(problems + ' problem(s) found'); process.exitCode = 1; }

/* 2. service worker with a content hash so phones update when content changes */
const hash = crypto.createHash('sha1'); files.forEach(f => hash.update(fs.readFileSync(path.join(APP, f))));
const version = 'leseli-' + LES.version + '-' + hash.digest('hex').slice(0, 8);
fs.writeFileSync(path.join(APP, 'sw.js'), `/* generated by tools/build.js – offline cache for the web/PWA version */
const CACHE = '${version}';
const FILES = ${JSON.stringify(['./'].concat(files), null, 0)};
self.addEventListener('install', e => e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())));
self.addEventListener('activate', e => e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener('fetch', e => { if (e.request.method !== 'GET') return; e.respondWith(caches.match(e.request, { ignoreSearch: true }).then(r => r || fetch(e.request).then(res => { const copy = res.clone(); caches.open(CACHE).then(c => c.put(e.request, copy)); return res; }).catch(() => caches.match('./index.html')))); });
`);
console.log('✔ sw.js', version, '(' + files.length + ' files)');

/* 3. copy into the Android project (assets/www) */
const AS = path.join(ROOT, 'android', 'app', 'src', 'main', 'assets', 'www');
if (fs.existsSync(path.join(ROOT, 'android'))) {
  fs.rmSync(AS, { recursive: true, force: true });
  files.forEach(f => { const to = path.join(AS, f); fs.mkdirSync(path.dirname(to), { recursive: true }); fs.copyFileSync(path.join(APP, f), to); });
  console.log('✔ copied app into android/app/src/main/assets/www');
}

/* 4. single-file version (share by WhatsApp/Bluetooth, open in Chrome, works offline) */
fs.mkdirSync(DIST, { recursive: true });
let one = html.replace(/<link rel="stylesheet" href="([^"]+)">/, (m, f) => '<style>\n' + fs.readFileSync(path.join(APP, f), 'utf8') + '\n</style>')
  .replace(/<link rel="manifest"[^>]*>\n?/, '').replace(/<link rel="(icon|apple-touch-icon)"[^>]*>\n?/g, '')
  .replace(/<script src="([^"]+)"><\/script>/g, (m, f) => '<script>\n' + fs.readFileSync(path.join(APP, f), 'utf8').replace(/<\/script/gi, '<\\/script') + '\n</script>');
one = one.replace('</head>', `<link rel="icon" href="data:image/svg+xml;base64,${fs.readFileSync(path.join(APP, 'icons/icon.svg')).toString('base64')}">\n</head>`);
fs.writeFileSync(path.join(DIST, 'leseli-offline.html'), one);
console.log('✔ dist/leseli-offline.html', Math.round(one.length / 1024) + ' KB');
